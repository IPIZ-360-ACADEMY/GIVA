export function createTranslator(language) {
  const safeLanguage = language === "pt-PT" || language === "en" ? language : "pt-BR";
  const current = TRANSLATIONS[safeLanguage];
  const fallback = TRANSLATIONS["pt-BR"];

  return function translate(key) {
    return current[key] ?? fallback[key] ?? key;
  };
}

export function resolveDateLocale(language) {
  if (language === "en") {
    return "en-US";
  }
  if (language === "pt-PT") {
    return "pt-PT";
  }
  return "pt-BR";
}


